# Replace "- 💭" blocks with "> [!note] 💭 我的想法"
# We need to match "- 💭" and following lines that are indented or part of the thought.
# Actually, looking at the text, the thoughts are:
# - 💭 ...
#    ...
#    ...
# until a blank line or another > or -

def replace_thought(match):
    text = match.group(0)
    lines = text.split('\n')
    new_lines = []
    for i, line in enumerate(lines):
        if i == 0:
            new_lines.append(line.replace('- 💭', '> [!note] 💭 我的想法\n>'))
        else:
            if line.strip() == '':
                new_lines.append('>')
            else:
                # remove leading spaces and add >
                new_lines.append('> ' + line.strip())
    return '\n'.join(new_lines)

